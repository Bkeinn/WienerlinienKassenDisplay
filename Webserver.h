// ── API: GET /api/rbl-lines → proxy to till.mabe.at/rbl/ (line list) ──

void handleApiRblLines(WebServer &server) {
    String html = fetchPage("https://till.mabe.at/rbl/");
    if(html.length() == 0) {
        server.send(502, "application/json", "{\"error\":\"Upstream fetch failed\"}");
        return;
    }

    // Find <select id="line"> or first <select>
    int selPos = html.indexOf("<select id=\"line\"");
    if(selPos < 0) selPos = html.indexOf("<select id='line'");
    if(selPos < 0) selPos = html.indexOf("<select");

    if(selPos < 0) {
        server.send(200, "application/json", "[]");
        return;
    }
    int closeSel = html.indexOf("</select>", selPos);
    if(closeSel < 0) { server.send(200, "application/json", "[]"); return; }

    String block = html.substring(selPos, closeSel);
    String json;
    json.reserve(block.length());  // pre-allocate (upper bound)
    json += '[';
    bool first = true;
    int pos = 0;

    while(true) {
        int optStart = block.indexOf("<option", pos);
        if(optStart < 0) break;
        int optEnd = block.indexOf("</option>", optStart);
        if(optEnd < 0) break;

        String tag = block.substring(optStart, optEnd);

        // value="..."
        int vS = tag.indexOf("value=\"");
        if(vS < 0) { pos = optEnd + 9; continue; }
        vS += 7;
        int vE = tag.indexOf('"', vS);
        if(vE < 0) { pos = optEnd + 9; continue; }
        String val = tag.substring(vS, vE);
        if(val.length() == 0) { pos = optEnd + 9; continue; }

        // inner text
        int tS = tag.indexOf('>', vE);
        if(tS < 0) { pos = optEnd + 9; continue; }
        tS++;
        String name = tag.substring(tS);
        name.trim();

        // JSON-escape: backslash and double-quote in name
        name.replace("\\", "\\\\");
        name.replace("\"", "\\\"");

        if(!first) json += ',';
        first = false;
        json += "{\"id\":\"";
        json += val;
        json += "\",\"name\":\"";
        json += name;
        json += "\"}";

        pos = optEnd + 9;
    }
    json += ']';
    server.send(200, "application/json", json);
}

