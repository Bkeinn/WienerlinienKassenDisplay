// ── Alert API ───────────────────────────────────────────────────

void handleApiGetAlerts(WebServer &server) {
    String json = EEPROMWIENERLINIEN::loadAlertsJSON();

    // Optional filter by stopid
    if (server.hasArg("stopid")) {
        int stopid = fastParseInt(server.arg("stopid").c_str(), server.arg("stopid").length());
        JsonDocument doc;
        deserializeJson(doc, json);
        JsonArray all = doc.as<JsonArray>();
        for (JsonObject entry : all) {
            if (entry["stopid"].as<int>() == stopid) {
                String filtered;
                serializeJson(entry, filtered);
                server.send(200, "application/json", filtered);
                return;
            }
        }
        server.send(200, "application/json", "{\"stopid\":" + String(stopid) + ",\"rules\":[]}");
        return;
    }

    server.send(200, "application/json", json);
}

void handleApiSaveAlerts(WebServer &server) {
    if (!server.hasArg("plain")) {
        server.send(400, "application/json", "{\"error\":\"Missing JSON body\"}");
        return;
    }

    String body = server.arg("plain");
    JsonDocument newEntry;
    DeserializationError err = deserializeJson(newEntry, body);
    if (err) {
        server.send(400, "application/json", "{\"error\":\"Invalid JSON\"}");
        return;
    }

    int stopid = newEntry["stopid"] | 0;
    if (stopid == 0) {
        server.send(400, "application/json", "{\"error\":\"Missing stopid\"}");
        return;
    }

    JsonArray newRules = newEntry["rules"].as<JsonArray>();

    // Load existing, rebuild merging in the new/updated entry
    String existing = EEPROMWIENERLINIEN::loadAlertsJSON();
    JsonDocument allDoc;
    deserializeJson(allDoc, existing);
    JsonArray oldAll = allDoc.as<JsonArray>();

    JsonDocument outDoc;
    JsonArray outArr = outDoc.to<JsonArray>();

    for (JsonObject entry : oldAll) {
        if (entry["stopid"].as<int>() != stopid) {
            outArr.add(entry);
        }
    }

    // Add/replace entry if it has rules
    if (newRules && newRules.size() > 0) {
        JsonObject obj = outArr.add<JsonObject>();
        obj["stopid"] = stopid;
        JsonArray copiedRules = obj["rules"].to<JsonArray>();
        for (JsonObject rule : newRules) {
            copiedRules.add(rule);
        }
    }

    String out;
    serializeJson(outDoc, out);
    EEPROMWIENERLINIEN::saveAlertsJSON(out);
    server.send(200, "application/json", "{\"status\":\"ok\"}");
}

// ── Legacy helpers (kept for potential external callers) ─────────

bool stopid_validator(String &numbers) {
    for(char c : numbers)
        if(!((c >= '0' && c <= '9') || c == ',' || c == ' ')) return false;
    return numbers.length() > 0;
}

std::vector<int> parse_num_vec(String &numbers) {
    std::vector<int> out;
    int cur = 0;
    bool has = false;
    for(char c : numbers) {
        if(c == ' ') continue;
        if(c == ',') { if(has) { out.push_back(cur); cur = 0; has = false; } }
        else { cur = cur * 10 + (c - '0'); has = true; }
    }
    if(has) out.push_back(cur);
    return out;
}
