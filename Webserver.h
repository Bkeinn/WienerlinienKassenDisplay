        // data-dir="..."
        String dir;
        int dS = tag.indexOf("data-dir=\"");
        if(dS >= 0) {
            dS += 10;
            int dE = tag.indexOf('"', dS);
            if(dE >= 0) dir = tag.substring(dS, dE);
        }

        // inner text
        int tS = tag.indexOf('>', vE);
