// ── Shared helper: fetch a URL, return body or empty string ──────

String fetchPage(const char* url) {
    HTTPClient http;
    http.useHTTP10(true);
    http.setTimeout(8000);
    http.begin(url);
    http.setUserAgent("ESP32-Proxy/1.0");
    String body;
    if(http.GET() == HTTP_CODE_OK) body = http.getString();
    http.end();
    return body;
}

// ── Helper: safe extract of LineStop.name (max 3 chars, null‑terminated) ──

String lineStopName(const WienerLinienStation::LineStop& ls) {
    String s;
    s.reserve(3);
    for(char c : ls.name) { if(c == '\0') break; s += c; }
    return s;
}

// ── Helper: fast integer parse from a char range ─────────────────

int fastParseInt(const char* s, size_t len) {
    int v = 0;
    for(size_t i = 0; i < len && s[i] >= '0' && s[i] <= '9'; i++)
        v = v * 10 + (s[i] - '0');
    return v;
}

