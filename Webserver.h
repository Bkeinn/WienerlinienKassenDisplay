// ── API: POST /api/add-stop → resolve RBL/StopId + add to list ──
// Form fields: line, station, name, dir, linename

void handleApiAddStop(WebServer &server, WienerLinienStation &station) {
    if(!server.hasArg("line") || !server.hasArg("station")) {
        server.send(400, "application/json", "{\"error\":\"Missing 'line' or 'station'\"}");
        return;
    }

    String lineParam    = server.arg("line");
    String stationParam = server.arg("station");
    String stationName  = server.arg("name");
    String lineName     = server.arg("linename");

    // Build upstream URL and fetch
    String url = "https://till.mabe.at/rbl/?line=";
    url += lineParam;
    url += "&station=";
    url += stationParam;

    String page = fetchPage(url.c_str());
    if(page.length() == 0) {
        server.send(502, "application/json", "{\"error\":\"Upstream fetch failed\"}");
        return;
    }

    // Parse RBL/StopId: <big>NNNN</big>
    int stopid = 0;
    int rblPos = page.indexOf("RBL/StopId: <big>");
    if(rblPos >= 0) {
        rblPos += 17;  // skip "RBL/StopId: <big>"
        while(rblPos < (int)page.length() && page[rblPos] >= '0' && page[rblPos] <= '9') {
            stopid = stopid * 10 + (page[rblPos] - '0');
            rblPos++;
        }
    }

    if(stopid == 0) {
        server.send(404, "application/json",
            "{\"error\":\"RBL/StopId not found — try a different station\"}");
        return;
    }

    // Build LineStop
    WienerLinienStation::LineStop ls;
    ls.stopid = stopid;
    ls.linecode = fastParseInt(lineParam.c_str(), lineParam.length());

    for(auto& saved_ls : station.linestopList) {
        if(ls.stopid == saved_ls.stopid && ls.linecode == saved_ls.linecode){
            String resp = "{\"status\":\"ok\",\"stopid\":";
            resp += stopid;
            resp += ",\"duplicate\":true}";
            server.send(200, "application/json", resp);
            return;
        }
    }


    // Copy up to 3 chars of line name into ls.name
    size_t n = (lineName.length() < 3) ? lineName.length() : 3;
    for(size_t i = 0; i < 3; i++)
        ls.name[i] = (i < n) ? lineName[i] : '\0';

    // Store human-readable station name (in-memory + EEPROM)
    if(stationName.length() > 0) {
        station.stopName[stopid] = stationName;
        EEPROMWIENERLINIEN::saveStationName(stopid, stationName);
    }

    EEPROMWIENERLINIEN::add(ls.save());
    station.linestopList.push_back(ls);

    String resp = "{\"status\":\"ok\",\"stopid\":";
    resp += stopid;
    resp += '}';
    server.send(200, "application/json", resp);
}

// ── API: POST /api/delete-stop → remove from list ────────────────
// Form field: id

void handleApiDeleteStop(WebServer &server, WienerLinienStation &station) {
    if(!server.hasArg("id")) {
        server.send(400, "application/json", "{\"error\":\"Missing 'id'\"}");
        return;
    }
    int id = fastParseInt(server.arg("id").c_str(), server.arg("id").length());

    auto& vec = station.linestopList;
    for(auto it = vec.begin(); it != vec.end(); ++it) {
        if(it->stopid == id) {
            // Persist removal: need save data before erasing iterator
            auto saveData = it->save();
            EEPROMWIENERLINIEN::remove(saveData);
            EEPROMWIENERLINIEN::removeStationName(id);
            vec.erase(it);
            server.send(200, "application/json", "{\"status\":\"ok\"}");
            return;
        }
    }
    server.send(404, "application/json", "{\"error\":\"Stop not found\"}");
}

